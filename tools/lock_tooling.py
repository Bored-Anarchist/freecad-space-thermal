"""Refresh hashes for explicitly pinned tooling from official PyPI JSON metadata."""
import json
from pathlib import Path
from urllib.request import urlopen

PINS = {"attrs": "24.3.0", "cmake": "3.31.6", "jsonschema": "4.23.0",
        "jsonschema-specifications": "2024.10.1", "ninja": "1.11.1.4",
        "referencing": "0.36.2", "rpds-py": "0.23.1", "setuptools": "78.1.0",
        "typing-extensions": "4.13.2", "PyYAML": "6.0.2"}


def main():
    lines = ["# Python 3.11 standalone tooling. Generated by tools/lock_tooling.py.",
             "# All published wheel hashes for these exact versions; source distributions excluded."]
    for name, version in sorted(PINS.items()):
        with urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as response:
            metadata = json.load(response)
        hashes = sorted({item["digests"]["sha256"] for item in metadata["urls"] if item["filename"].endswith(".whl")})
        if not hashes:
            raise SystemExit("No wheels found for pinned dependency")
        lines.append(f"{name}=={version} \\")
        lines.extend("    --hash=sha256:" + value + (" \\" if i < len(hashes) - 1 else "")
                     for i, value in enumerate(hashes))
    target = Path(__file__).resolve().parents[1] / "ci/requirements.lock"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("Pinned tooling hashes refreshed")


if __name__ == "__main__":
    main()
